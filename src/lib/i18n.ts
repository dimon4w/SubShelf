export type Lang = 'ru' | 'en'
const DICTS: Record<Lang, Record<Key, string>> = { ru, en }

export interface I18n {
  lang: Lang
  locale: string
  t: (key: Key, vars?: Record<string, string | number>) => string
}

export function resolveLang(pref: LangPref): Lang {
  if (pref === 'ru' || pref === 'en') return pref
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'ru'
  return nav.startsWith('en') ? 'en' : 'ru'
}

export function makeI18n(lang: Lang): I18n {
  const dict = DICTS[lang]
  return {
    lang,
    locale: lang === 'ru' ? 'ru-RU' : 'en-US',
    t: (key, vars) => {
      let s = dict[key] ?? ru[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
  }
}

export const I18nContext = createContext<I18n>(makeI18n('ru'))
export const useI18n = () => useContext(I18nContext)
