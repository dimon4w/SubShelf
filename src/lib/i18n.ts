export type Lang = 'ru' | 'en'
export type T = (key: Key, vars?: Record<string, string | number>) => string

export interface I18n {
  lang: Lang
  locale: string
  t: T
  days: (n: number) => string
}

export function resolveLang(pref: LangPref): Lang {
  if (pref !== 'system') return pref
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'ru'
  return nav.startsWith('en') ? 'en' : 'ru'
}

function ruPlural(n: number, forms: [string, string, string]): string {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return forms[2]
  if (b > 1 && b < 5) return forms[1]
  if (b === 1) return forms[0]
  return forms[2]
}

export function makeI18n(lang: Lang): I18n {
  const dict = lang === 'en' ? en : ru
  const t: T = (key, vars) => {
    let s = dict[key]
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
  return {
    lang,
    locale: lang === 'en' ? 'en-US' : 'ru-RU',
    t,
    days: (n) =>
      lang === 'en' ? (Math.abs(n) === 1 ? 'day' : 'days') : ruPlural(n, ['день', 'дня', 'дней']),
  }
}

export const I18nContext = createContext<I18n>(makeI18n('ru'))
export const useI18n = () => useContext(I18nContext)
